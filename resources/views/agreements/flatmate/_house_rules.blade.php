<h2 class="section">House Rules</h2>

<h3 class="tc-head">Purpose</h3>
<p>These rules are established to protect the property, maintain a comfortable and safe living environment, and promote respect and cooperation among all occupants.</p>

<h3 class="tc-head">General House Rules</h3>

<h3 class="tc-head">1. GENERAL CONDUCT</h3>
<p class="clause"><span class="n">1.1</span> All occupants must behave respectfully and responsibly.</p>
<p class="clause"><span class="n">1.2</span> The following conduct is prohibited:</p>
<ul class="bullets">
    <li>threatening behaviour;</li>
    <li>harassment;</li>
    <li>intimidation;</li>
    <li>violence;</li>
    <li>abusive or discriminatory behaviour;</li>
    <li>serious or repeated disturbance;</li>
    <li>deliberate damage;</li>
    <li>unlawful activity; or</li>
    <li>conduct creating an unreasonable risk to people or property.</li>
</ul>
<p class="clause"><span class="n">1.3</span> Occupants must respect the privacy, belongings, sleep, work, study, and reasonable enjoyment of other occupants.</p>

<h3 class="tc-head">2. GUESTS AND VISITORS</h3>
<p class="clause"><span class="n">2.1</span> Guests are permitted only in accordance with the Agreement and reasonable Property requirements.</p>
<p class="clause"><span class="n">2.2</span> The Tenant is responsible for the behaviour of their guests.</p>
<p class="clause"><span class="n">2.3</span> Guests must not be allowed to permanently or repeatedly occupy the Property as though they were tenants or approved occupants.</p>
<p class="clause"><span class="n">2.4</span> The Tenant must not provide keys, access codes, or security devices to unauthorised persons.</p>
<p class="clause"><span class="n">2.5</span> Any guest-related conduct that causes disturbance, damage, security concerns, or unreasonable disruption may result in action under the Agreement.</p>

<h3 class="tc-head">3. NOISE AND DISTURBANCE</h3>
<p class="clause"><span class="n">3.1</span> Occupants must keep noise at a reasonable level at all times.</p>
<p class="clause"><span class="n">3.2</span> Particular care must be taken during reasonable quiet periods, including overnight.</p>
<p class="clause"><span class="n">3.3</span> Loud music, shouting, parties, excessive gatherings, or other disruptive activities are not permitted.</p>
<p class="clause"><span class="n">3.4</span> Occupants must not create unreasonable noise that disturbs other occupants or neighbours.</p>

<h3 class="tc-head">4. CLEANLINESS OF ROOMS AND SHARED AREAS</h3>
<p class="clause"><span class="n">4.1</span> Each Tenant is responsible for maintaining their room in a clean and hygienic condition.</p>
<p class="clause"><span class="n">4.2</span> Shared areas must be cleaned immediately after use.</p>
<p class="clause"><span class="n">4.3</span> Kitchen surfaces, bathrooms, dining areas, lounge areas, appliances, and other shared facilities must not be left dirty or unusable.</p>
<p class="clause"><span class="n">4.4</span> Food, rubbish, dishes, clothing, shoes, bags, or personal belongings must not be left in shared areas in a manner that obstructs or unreasonably interferes with others.</p>
<p class="clause"><span class="n">4.5</span> Occupants must not intentionally create excessive mess or unhygienic conditions.</p>

<h3 class="tc-head">5. RUBBISH AND WASTE MANAGEMENT</h3>
<p class="clause"><span class="n">5.1</span> Rubbish must be placed in the appropriate bins.</p>
<p class="clause"><span class="n">5.2</span> Recycling must be separated where required.</p>
<p class="clause"><span class="n">5.3</span> Rubbish must not be allowed to accumulate inside bedrooms or common areas.</p>
<p class="clause"><span class="n">5.4</span> Occupants must follow the Property’s rubbish collection arrangements.</p>
<p class="clause"><span class="n">5.5</span> Items that cannot be placed in normal household rubbish must not be dumped at the Property.</p>

<h3 class="tc-head">6. USE OF PROPERTY AND FACILITIES</h3>
<p class="clause"><span class="n">6.1</span> All facilities must be used only for their intended purpose.</p>
<p class="clause"><span class="n">6.2</span> Occupants must not make structural changes or unauthorised alterations.</p>
<p class="clause"><span class="n">6.3</span> No drilling, permanent installation, painting, modification, or alteration is permitted without prior approval.</p>
<p class="clause"><span class="n">6.4</span> Appliances must be used responsibly and safely.</p>
<p class="clause"><span class="n">6.5</span> Occupants must immediately report malfunctioning or damaged appliances rather than continuing to use them where doing so may cause damage or injury.</p>

<h3 class="tc-head">7. SHARED BATHROOMS AND COMMON AREAS</h3>
<p class="clause"><span class="n">7.1</span> Shared bathrooms and common areas must be used respectfully.</p>
<p class="clause"><span class="n">7.2</span> Occupants must clean up after themselves.</p>
<p class="clause"><span class="n">7.3</span> Personal belongings must not unnecessarily occupy shared facilities.</p>
<p class="clause"><span class="n">7.4</span> Bathrooms must not be deliberately or unreasonably monopolised.</p>
<p class="clause"><span class="n">7.5</span> Occupants must maintain reasonable hygiene and consideration for others.</p>

<h3 class="tc-head">8. STORAGE AND PERSONAL BELONGINGS</h3>
<p class="clause"><span class="n">8.1</span> Personal belongings must be stored within the Tenant’s designated room or approved storage area.</p>
<p class="clause"><span class="n">8.2</span> Hallways, entrances, stairways, exits, fire routes, and other access areas must remain clear.</p>
<p class="clause"><span class="n">8.3</span> Valuable or irreplaceable belongings should not be left unattended in shared areas.</p>
<p class="clause"><span class="n">8.4</span> Exalt is not responsible for personal belongings except where legally responsible.</p>

<h3 class="tc-head">9. SMOKING AND VAPING</h3>
<p class="clause"><span class="n">9.1</span> Smoking and vaping inside bedrooms, bathrooms, kitchens, lounges, hallways, or other enclosed internal areas is prohibited.</p>
<p class="clause"><span class="n">9.2</span> Where permitted, smoking or vaping must take place only in designated or lawful outdoor areas.</p>
<p class="clause"><span class="n">9.3</span> Cigarette butts, ash, vaping products, and related waste must be disposed of safely.</p>
<p class="clause"><span class="n">9.4</span> Any damage, staining, odour, or additional cleaning caused by smoking or vaping may be treated in accordance with the Agreement and applicable law.</p>

<h3 class="tc-head">10. MOVING-OUT REQUIREMENTS</h3>
<p class="clause"><span class="n">10.1</span> Before leaving, the Tenant must:</p>
<ul class="bullets">
    <li>remove all belongings;</li>
    <li>remove rubbish;</li>
    <li>clean their room;</li>
    <li>clean any areas used by them;</li>
    <li>return keys and access devices;</li>
    <li>report damage; and</li>
    <li>follow Exalt’s move-out instructions.</li>
</ul>
<p class="clause"><span class="n">10.2</span> Items left behind may be dealt with in accordance with the Agreement and applicable law.</p>

<h3 class="tc-head">11. MAINTENANCE AND PROPERTY CARE</h3>
<p class="clause"><span class="n">11.1</span> Maintenance issues must be reported promptly.</p>
<p class="clause"><span class="n">11.2</span> Occupants must not ignore leaks, electrical issues, broken fixtures, pests, water damage, mould, security issues, or other conditions that could cause further damage.</p>
<p class="clause"><span class="n">11.3</span> Occupants must not undertake major repairs themselves without approval.</p>
<p class="clause"><span class="n">11.4</span> Damage caused by misuse, negligence, recklessness, intentional conduct, or breach may result in recovery of costs to the extent permitted by law.</p>

<h3 class="tc-head">12. COMPLIANCE WITH HOUSE RULES</h3>
<p class="clause"><span class="n">12.1</span> These House Rules are mandatory.</p>
<p class="clause"><span class="n">12.2</span> Repeated or serious breaches may constitute a breach of the Agreement.</p>
<p class="clause"><span class="n">12.3</span> Exalt may take reasonable action in response to breaches, subject to the Agreement and applicable law.</p>

<h3 class="tc-head">13. RELATIONSHIP TO THE AGREEMENT</h3>
<p class="clause"><span class="n">13.1</span> These House Rules form part of the Flatmate Agreement.</p>
<p class="clause"><span class="n">13.2</span> The Tenant agrees to comply with them throughout the accommodation period.</p>
<p class="clause"><span class="n">13.3</span> If a House Rule conflicts with a mandatory legal requirement, the legal requirement prevails.</p>

<h3 class="tc-head">14. MINOR MAINTENANCE AND CONSUMABLES</h3>
<p class="clause"><span class="n">14.1</span> Occupants must use consumables and household items responsibly.</p>
<p class="clause"><span class="n">14.2</span> Occupants must not remove household supplies from the Property for personal use elsewhere.</p>
<p class="clause"><span class="n">14.3</span> Any issue involving essential facilities or property systems should be reported to Exalt rather than independently repaired or replaced without approval.</p>

<h3 class="tc-head">15. INSPECTIONS</h3>
<p class="clause"><span class="n">15.1</span> Exalt may conduct lawful inspections in accordance with the Agreement.</p>
<p class="clause"><span class="n">15.2</span> Occupants must provide reasonable cooperation.</p>
<p class="clause"><span class="n">15.3</span> Inspections may include checking the general condition, cleanliness, maintenance requirements, safety, fixtures, appliances, and other relevant aspects of the Property.</p>

<h3 class="tc-head">16. COMMUNICATION</h3>
<p class="clause"><span class="n">16.1</span> The Tenant must maintain accurate contact details.</p>
<p class="clause"><span class="n">16.2</span> Important property matters must be communicated to Exalt promptly.</p>
<p class="clause"><span class="n">16.3</span> Emergency property issues must be reported immediately through the appropriate Exalt contact channel.</p>
<p class="clause"><span class="n">16.4</span> Failure to report a known issue that results in avoidable additional damage may be taken into account to the extent permitted by law.</p>

<h3 class="tc-head">17. PET POLICY</h3>
<p class="clause"><span class="n">17.1</span> Pets are permitted only where authorised under the Agreement and applicable law.</p>
<p class="clause"><span class="n">17.2</span> Where approval is required, the Tenant must obtain approval before bringing a pet onto the Property.</p>
<p class="clause"><span class="n">17.3</span> The Tenant is responsible for the behaviour, care, cleanliness, and damage caused by their pet to the extent permitted by law.</p>
<p class="clause"><span class="n">17.4</span> Pets must not create unreasonable noise, odour, damage, hygiene issues, safety risks, or disturbance.</p>

<h3 class="tc-head">18. CLEANING SUPPLIES</h3>
<p class="clause"><span class="n">18.1</span> Cleaning products and equipment provided for shared use must be used responsibly.</p>
<p class="clause"><span class="n">18.2</span> Occupants must not misuse, remove, damage, or deliberately waste cleaning supplies.</p>
<p class="clause"><span class="n">18.3</span> Tenants are expected to maintain reasonable cleanliness throughout their stay rather than leaving all cleaning until the end of the Agreement.</p>
<p class="clause"><span class="n">18.4</span> Additional cleaning caused by unreasonable mess, damage, or breach may be recoverable to the extent permitted by the Agreement and applicable law.</p>
