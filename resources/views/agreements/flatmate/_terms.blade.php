<h2 class="section">Terms &amp; Conditions</h2>

<h3 class="tc-head">1. AGREEMENT</h3>
<p class="clause"><span class="n">1.1</span> This Agreement governs the Tenant’s occupation of the entire Property identified in the Agreement.</p>
<p class="clause"><span class="n">1.2</span> The Tenant receives exclusive occupation of the Property, subject to Exalt’s and the owner’s lawful rights of access.</p>
<p class="clause"><span class="n">1.3</span> The Tenant agrees to comply with this Agreement, the applicable House Rules, written property instructions, and applicable New Zealand law.</p>
<p class="clause"><span class="n">1.4</span> The Agreement, together with its schedules and written variations, forms the complete agreement between the parties concerning the Property.</p>

<h3 class="tc-head">2. PARTIES AND RIGHT OF OCCUPATION</h3>
<p class="clause"><span class="n">2.1</span> The Tenant is granted the right to occupy the entire Property for residential purposes during the agreed term.</p>
<p class="clause"><span class="n">2.2</span> Only the persons expressly approved and recorded in the Agreement may ordinarily occupy the Property.</p>
<p class="clause"><span class="n">2.3</span> The Tenant must not assign, sublet, transfer, licence, or otherwise give another person exclusive possession of the Property without the required written approval and where permitted by law.</p>
<p class="clause"><span class="n">2.4</span> The Tenant must not use the Property for unlawful, hazardous, commercial, or unauthorised purposes.</p>
<p class="clause"><span class="n">2.5</span> The Tenant is responsible for the conduct of their household members, occupants, and guests to the extent permitted by law.</p>

<h3 class="tc-head">3. IDENTIFICATION AND CONTACT INFORMATION</h3>
<p class="clause"><span class="n">3.1</span> The Tenant must provide accurate identification and contact information.</p>
<p class="clause"><span class="n">3.2</span> The Tenant must promptly notify Exalt of material changes to their contact details, household composition, immigration/residency information where relevant, or other information required under the Agreement.</p>
<p class="clause"><span class="n">3.3</span> Providing false or misleading information may constitute a breach of the Agreement.</p>

<h3 class="tc-head">4. RENT AND PAYMENT OBLIGATIONS</h3>
<p class="clause"><span class="n">4.1</span> The Tenant must pay the agreed weekly rent in advance in accordance with the payment schedule stated in the Agreement.</p>
<p class="clause"><span class="n">4.2</span> Rent must be paid in full and on time.</p>
<p class="clause"><span class="n">4.3</span> The Tenant remains responsible for rent during temporary absence from the Property unless otherwise agreed or provided by law.</p>
<p class="clause"><span class="n">4.4</span> Utilities and other property-related charges will be payable as stated in the Agreement.</p>
<p class="clause"><span class="n">4.5</span> Where utilities are charged based on actual usage or invoices, the Tenant must pay the amount properly attributable to the Property or Tenant under the Agreement.</p>
<p class="clause"><span class="n">4.6</span> Failure to occupy the Property does not automatically suspend rent obligations.</p>
<p class="clause"><span class="n">4.7</span> Any payment dispute must be raised with Exalt promptly, but the Tenant must not unilaterally withhold rent except where legally entitled to do so.</p>

<h3 class="tc-head">5. BOND AND REFUNDABLE PAYMENTS</h3>
<p class="clause"><span class="n">5.1</span> Any bond or refundable payment will be stated in the Agreement.</p>
<p class="clause"><span class="n">5.2</span> Bond and other refundable amounts will be handled in accordance with applicable law.</p>
<p class="clause"><span class="n">5.3</span> Exalt may seek lawful deductions or recovery for unpaid rent, damage, missing items, cleaning, keys, or other amounts properly payable by the Tenant.</p>
<p class="clause"><span class="n">5.4</span> The Tenant remains responsible for lawful amounts exceeding any bond.</p>

<h3 class="tc-head">6. EXALT’S RESPONSIBILITIES</h3>
<p class="clause"><span class="n">6.1</span> Exalt will use reasonable efforts to manage the Property and respond to maintenance matters within its responsibility.</p>
<p class="clause"><span class="n">6.2</span> Exalt will communicate relevant property-management matters to the Tenant.</p>
<p class="clause"><span class="n">6.3</span> Exalt’s responsibilities are subject to applicable law, reasonable operational requirements, and matters outside Exalt’s control.</p>

<h3 class="tc-head">7. TENANT RESPONSIBILITIES</h3>
<p class="clause"><span class="n">7.1</span> The Tenant must:</p>
<ul class="bullets">
    <li>keep the Property reasonably clean and tidy;</li>
    <li>take reasonable care of the Property;</li>
    <li>promptly report maintenance issues;</li>
    <li>prevent avoidable damage;</li>
    <li>use appliances and fixtures appropriately;</li>
    <li>keep the Property secure;</li>
    <li>comply with the House Rules;</li>
    <li>pay rent and agreed charges on time; and</li>
    <li>comply with applicable laws.</li>
</ul>
<p class="clause"><span class="n">7.2</span> The Tenant must not deliberately, recklessly, negligently, or unreasonably damage the Property.</p>

<h3 class="tc-head">8. MAINTENANCE, REPAIRS AND COST RECOVERY</h3>
<p class="clause"><span class="n">8.1</span> Maintenance issues must be reported promptly.</p>
<p class="clause"><span class="n">8.2</span> The Tenant must not carry out structural, electrical, plumbing, security, or major repairs without approval, except where immediate action is reasonably necessary to protect people or property.</p>
<p class="clause"><span class="n">8.3</span> The Tenant must cooperate with reasonable maintenance arrangements.</p>
<p class="clause"><span class="n">8.4</span> Where the Tenant causes damage through misuse, negligence, recklessness, intentional conduct, or breach, Exalt may seek recovery to the extent permitted by law.</p>
<p class="clause"><span class="n">8.5</span> The Tenant must not engage unapproved contractors for work affecting the Property.</p>

<h3 class="tc-head">9. APPLIANCES, FIXTURES AND PROPERTY</h3>
<p class="clause"><span class="n">9.1</span> Fixtures and appliances supplied with the Property remain the property of the owner or Exalt, as applicable.</p>
<p class="clause"><span class="n">9.2</span> The Tenant must use supplied appliances and fixtures responsibly.</p>
<p class="clause"><span class="n">9.3</span> The Tenant must not remove, dispose of, modify, dismantle, or relocate supplied property without approval.</p>
<p class="clause"><span class="n">9.4</span> Unless specifically listed in the Agreement, the Property is provided without additional furniture or appliances.</p>
<p class="clause"><span class="n">9.5</span> Any supplied oven, stove, dishwasher, fixed appliance, fixture, or fitting remains with the Property.</p>

<h3 class="tc-head">10. RIGHT OF ENTRY</h3>
<p class="clause"><span class="n">10.1</span> Exalt, the owner, or an authorised person may enter the Property for lawful purposes in accordance with applicable law.</p>
<p class="clause"><span class="n">10.2</span> Where notice is required, the appropriate notice will be provided.</p>
<p class="clause"><span class="n">10.3</span> Access may be required for:</p>
<ul class="bullets">
    <li>inspections;</li>
    <li>repairs;</li>
    <li>maintenance;</li>
    <li>safety;</li>
    <li>compliance;</li>
    <li>valuation;</li>
    <li>authorised viewings;</li>
    <li>property management; or</li>
    <li>emergencies.</li>
</ul>
<p class="clause"><span class="n">10.4</span> The Tenant must not unreasonably prevent lawful access.</p>

<h3 class="tc-head">11. KEYS AND SECURITY</h3>
<p class="clause"><span class="n">11.1</span> The Tenant is responsible for all keys, remotes, access devices, and security information provided.</p>
<p class="clause"><span class="n">11.2</span> Keys and access devices must not be copied or transferred without approval.</p>
<p class="clause"><span class="n">11.3</span> Lost keys or access devices must be reported immediately.</p>
<p class="clause"><span class="n">11.4</span> The Tenant may be responsible for reasonable replacement or security costs caused by their loss or misuse where permitted by law.</p>
<p class="clause"><span class="n">11.5</span> The Tenant must not change locks or security systems without approval.</p>

<h3 class="tc-head">12. RENT DURING ABSENCE</h3>
<p class="clause"><span class="n">12.1</span> Rent remains payable during temporary absence unless otherwise agreed or provided by law.</p>
<p class="clause"><span class="n">12.2</span> Holidays, travel, work commitments, or other temporary absence do not automatically terminate the Agreement.</p>
<p class="clause"><span class="n">12.3</span> The Tenant should notify Exalt of extended absence for security and property-management purposes.</p>

<h3 class="tc-head">13. INSURANCE AND LIABILITY</h3>
<p class="clause"><span class="n">13.1</span> The Tenant is responsible for their own belongings and should maintain appropriate contents and liability insurance.</p>
<p class="clause"><span class="n">13.2</span> The Tenant remains responsible for loss or damage caused by their actions or those of their household members or guests to the extent permitted by law.</p>
<p class="clause"><span class="n">13.3</span> Exalt is not responsible for personal property except where legally responsible.</p>
<p class="clause"><span class="n">13.4</span> Nothing in this Agreement excludes liability that cannot legally be excluded.</p>

<h3 class="tc-head">14. FIXED TERM AND EARLY TERMINATION</h3>
<p class="clause"><span class="n">14.1</span> The Agreement continues for the fixed term stated in the Agreement unless lawfully ended earlier.</p>
<p class="clause"><span class="n">14.2</span> The Tenant acknowledges the commitment created by entering into a fixed-term Agreement.</p>
<p class="clause"><span class="n">14.3</span> If the Tenant wishes to leave early, the Tenant must contact Exalt and follow the applicable legal and contractual process.</p>
<p class="clause"><span class="n">14.4</span> The Tenant may request an agreed early termination or other lawful arrangement.</p>
<p class="clause"><span class="n">14.5</span> Physical departure does not automatically terminate the Agreement.</p>
<p class="clause"><span class="n">14.6</span> Any agreement to release the Tenant from future obligations must be confirmed in writing.</p>
<p class="clause"><span class="n">14.7</span> Any early-termination costs must be limited to amounts lawfully recoverable.</p>

<h3 class="tc-head">15. GENERAL PROVISIONS</h3>
<p class="clause"><span class="n">15.1</span> The Tenant must comply with the Agreement, House Rules, and applicable law.</p>
<p class="clause"><span class="n">15.2</span> The Property must be used only for lawful residential purposes unless otherwise agreed.</p>
<p class="clause"><span class="n">15.3</span> The Tenant must not create unreasonable risk, nuisance, damage, or disturbance.</p>
<p class="clause"><span class="n">15.4</span> Failure by Exalt to enforce a provision immediately does not constitute automatic waiver.</p>
<p class="clause"><span class="n">15.5</span> Variations should be confirmed in writing.</p>
<p class="clause"><span class="n">15.6</span> If any provision is unenforceable, the remaining provisions continue to the extent permitted by law.</p>

<h3 class="tc-head">16. PROPERTY INSPECTIONS</h3>
<p class="clause"><span class="n">16.1</span> Exalt may conduct lawful inspections in accordance with applicable law.</p>
<p class="clause"><span class="n">16.2</span> The Tenant must cooperate with reasonable inspection arrangements.</p>
<p class="clause"><span class="n">16.3</span> Inspections may assess the Property’s condition, cleanliness, maintenance, safety, fixtures, appliances, and compliance with the Agreement.</p>

<h3 class="tc-head">17. CLEANING AND MAINTENANCE</h3>
<p class="clause"><span class="n">17.1</span> The Tenant is responsible for maintaining the entire Property in a reasonably clean and hygienic condition.</p>
<p class="clause"><span class="n">17.2</span> This includes, where applicable:</p>
<ul class="bullets">
    <li>bedrooms;</li>
    <li>bathrooms;</li>
    <li>kitchen;</li>
    <li>lounge;</li>
    <li>hallways;</li>
    <li>laundry areas;</li>
    <li>outdoor areas;</li>
    <li>lawns and gardens; and</li>
    <li>other areas provided as part of the Property.</li>
</ul>
<p class="clause"><span class="n">17.3</span> The Tenant must promptly address unreasonable mess, rubbish, spills, or conditions that could cause damage.</p>
<p class="clause"><span class="n">17.4</span> Additional cleaning or restoration caused by the Tenant may be recoverable where permitted by law.</p>

<h3 class="tc-head">18. END OF FIXED TERM / VACATING</h3>
<p class="clause"><span class="n">18.1</span> At the end of the Agreement, the Tenant must vacate the entire Property by the agreed date and time unless a lawful continuation or written extension applies.</p>
<p class="clause"><span class="n">18.2</span> The Tenant must:</p>
<ul class="bullets">
    <li>remove all belongings;</li>
    <li>remove all rubbish;</li>
    <li>clean the Property;</li>
    <li>return all keys and access devices;</li>
    <li>leave supplied appliances and fixtures in place;</li>
    <li>report outstanding damage or maintenance matters; and</li>
    <li>leave the Property in the condition required by the Agreement and applicable law.</li>
</ul>
<p class="clause"><span class="n">18.3</span> The Tenant must not leave belongings behind without written agreement.</p>
<p class="clause"><span class="n">18.4</span> Any continuation, renewal, extension, or holding over will be dealt with in accordance with the Agreement and applicable law.</p>
<p class="clause"><span class="n">18.5</span> Any outstanding rent, utilities, damage, cleaning, or other lawful amounts must be settled in accordance with the Agreement.</p>

